"""Inventario local reproducible; solo stdlib, sin importar clientes ni el pipeline.

El JSON y Markdown son derivados técnicos, no un registro jurídico ni un índice
vivo. La herramienta solo escribe esos dos informes cuando se solicita --write.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import os
import re
import tempfile
import unicodedata
from collections import Counter, defaultdict
from collections.abc import Iterator
from pathlib import Path
from typing import Any, NoReturn
from urllib.parse import quote, unquote, urlsplit

GENERATOR = "utils.audit_local_corpus"
MARKDOWN_MARKER = f"<!-- Generated by {GENERATOR}; do not edit manually. -->"
OUTPUT_NAMES = ("corpus-catalog.json", "CORPUS_CATALOG.md")
LAYERS = {"raw": {".pdf", ".md"}, "bronze": {".md"}, "silver": {".jsonl"}, "gold": {".jsonl"}}
DOC_TYPES = {"jurisprudencia", "normativa"}
DESCRIPTIVE_FIELDS = ("title", "Corporación", "Radicado", "Magistrado ponente", "Tema principal")
# Gramática acotada: destinos simples/entre <...> y títulos delimitados.
# Una cola de palabras sin delimitar nunca se interpreta como título.
IMAGE_START = re.compile(r"!\[[^\]\r\n]*\]\(")
IMAGE_LINK = re.compile(
    IMAGE_START.pattern
    + r"""[ \t]*(?:<([^<>\r\n]+)>|([^\s()<>]+))"""
    + r"""(?:[ \t]+(?:"[^"\r\n]*"|'[^'\r\n]*'|\([^()\r\n]*\)))?[ \t]*\)"""
)
LEGACY_IMAGE_LINK = re.compile(IMAGE_START.pattern + r"""([^()<>"'\x00-\x1f\x7f]+)\)""")
IMAGE_EXTENSIONS = {".png", ".jpg", ".jpeg", ".gif", ".webp", ".bmp", ".tif", ".tiff", ".svg"}


def _digest(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def _value_digest(value: Any) -> str:
    encoded = json.dumps(value, ensure_ascii=False, sort_keys=True, allow_nan=False).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def _relative(path: Path, project_root: Path) -> str:
    return path.relative_to(project_root).as_posix()


def _finding(
    findings: list[dict],
    code: str,
    path: str,
    detail: str,
    *,
    error: bool = False,
    line: int | None = None,
) -> None:
    item: dict[str, Any] = {
        "severity": "error" if error else "warning",
        "code": code,
        "path": path,
        "detail": detail,
    }
    if line is not None:
        item["line"] = line
    findings.append(item)


def _reject_constant(value: str) -> NoReturn:
    raise ValueError(f"Constante JSON no válida: {value}")


def _reject_duplicate_keys(pairs: list[tuple[str, Any]]) -> dict:
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Clave JSON repetida: {key}")
        result[key] = value
    return result


def _loads(text: str) -> Any:
    return json.loads(
        text, parse_constant=_reject_constant, object_pairs_hook=_reject_duplicate_keys
    )


def _records(path: Path, findings: list[dict], label: str) -> Iterator[tuple[int, dict]]:
    opener = gzip.open if path.suffix == ".gz" else open
    try:
        with opener(path, "rt", encoding="utf-8") as stream:
            for number, line in enumerate(stream, 1):
                if not line.strip():
                    continue
                try:
                    value = _loads(line)
                    if not isinstance(value, dict):
                        raise ValueError("Se esperaba un objeto JSON")
                except ValueError as exc:
                    _finding(
                        findings, "invalid_json_record", label, str(exc), error=True, line=number
                    )
                    continue
                yield number, value
    except (OSError, EOFError, UnicodeError) as exc:
        raise ValueError(f"No se puede leer {label}: {type(exc).__name__}") from exc


def _metadata_hashes(
    metadata: dict, *, gold: bool, structured_fields: frozenset[str] = frozenset()
) -> dict[str, str]:
    """Comparación semántica, sin copiar contenido ni importar el backend.

    Contrato observado en core/vectorstore.py: Gold omite None, serializa
    listas/dicts y deriva keywords_str. Además de keywords/entities, el export
    decodifica solo campos que eran listas/dicts en Gold. No se interpretan
    referencias jurídicas textuales como JSON ni se convierten a números.
    """
    values = dict(metadata)
    if gold:
        values = {key: value for key, value in values.items() if value is not None}
        if isinstance(values.get("keywords"), list):
            if not all(isinstance(value, str) for value in values["keywords"]):
                raise ValueError("keywords contiene valores no textuales")
            values["keywords_str"] = ", ".join(values["keywords"])
    for key in {"keywords", "entities"} | structured_fields:
        if isinstance(values.get(key), str):
            try:
                decoded = _loads(values[key])
            except ValueError:
                continue
            if isinstance(decoded, (list, dict)):
                values[key] = decoded
    return {key: _value_digest(value) for key, value in values.items()}


def _inventory(corpus: Path, project_root: Path) -> list[dict]:
    entries = []
    for path in sorted(corpus.rglob("*")):
        if path.is_symlink():
            raise ValueError(f"No se siguen enlaces simbólicos: {_relative(path, project_root)}")
        if path.is_file():
            entries.append(
                {
                    "path": _relative(path, project_root),
                    "bytes": path.stat().st_size,
                    "sha256": _digest(path),
                }
            )
    return entries


def _new_document(path: str, doc_type: str) -> dict:
    return {
        "source_path": path,
        "doc_type": doc_type,
        "artifacts": {},
        "coverage": "not_verified",
        "observed_metadata": {},
        "gold_chunks": 0,
        "export_records_matched_by_id": 0,
        "export_text_mismatches": 0,
        "export_metadata_differences": {},
        "gold_ids_missing_export": 0,
    }


def _image_path(parent: Path, target: str, corpus: Path) -> tuple[Path, str | None]:
    """Recorrer componentes locales sin resolver ni atravesar symlinks."""
    candidate = parent / target
    image = corpus
    if not candidate.is_relative_to(corpus) or not Path(os.path.abspath(candidate)).is_relative_to(
        corpus
    ):
        return candidate, "image_outside_corpus"
    for part in candidate.relative_to(corpus).parts:
        image = image.parent if part == ".." else image / part
        if not image.is_relative_to(corpus):
            return image, "image_outside_corpus"
        if image.is_symlink():
            return image, "image_symlink"
    # Mantener los segmentos originales para comprobar también la existencia
    # de los directorios intermedios; no colapsar "inexistente/../imagen.png".
    return candidate, None


def _audit_images(
    text: str, path: Path, project_root: Path, corpus: Path, findings: list[dict]
) -> None:
    """Inspeccionar referencias inline, sin parser general ni seguir symlinks."""
    label = _relative(path, project_root)
    line, offset = 1, 0
    for start in IMAGE_START.finditer(text):
        line += text.count("\n", offset, start.start())
        offset = start.start()
        match = IMAGE_LINK.match(text, start.start())
        legacy = match is None
        if match is not None:
            target = match.group(1) or match.group(2)
        else:
            match = LEGACY_IMAGE_LINK.match(text, start.start())
            target = match.group(1) if match is not None else ""
        try:
            url = urlsplit(target)
        except ValueError:
            target = ""
        if not target or (
            legacy
            and (
                " " not in target
                or target != target.strip(" ")
                or Path(target).suffix.lower() not in IMAGE_EXTENSIONS
                or url.scheme
                or url.netloc
                or Path(target).is_absolute()
            )
        ):
            _finding(
                findings,
                "unsupported_image_syntax",
                label,
                "Referencia inline fuera de la gramática soportada; no se infiere el destino",
                line=line,
            )
            continue
        if url.scheme or url.netloc:
            continue
        if legacy:
            _finding(findings, "unescaped_image_path", label, target, line=line)
        image, issue = _image_path(path.parent, unquote(url.path), corpus)
        if issue is not None:
            _finding(findings, issue, label, target, error=True, line=line)
        elif not image.is_file():
            _finding(findings, "missing_image", label, target, line=line)


def _collect_documents(
    files: list[dict], project_root: Path, corpus: Path, findings: list[dict]
) -> tuple[list[dict], dict[str, dict], list[list[str]], int]:
    documents: list[dict] = []
    owners: dict[tuple[str, str], list[dict]] = defaultdict(list)
    artifacts: dict[tuple[str, str, str], list[str]] = defaultdict(list)
    duplicates: dict[str, list[str]] = defaultdict(list)
    folded_names: dict[tuple[str, str], list[str]] = defaultdict(list)
    source_count = 0
    for entry in files:
        path = project_root / entry["path"]
        parts = path.relative_to(corpus).parts
        if entry["bytes"] == 0:
            _finding(findings, "empty_file", entry["path"], "Archivo vacío", error=True)
        if len(parts) < 3 or parts[0] not in LAYERS or path.suffix.lower() not in LAYERS[parts[0]]:
            continue
        layer, doc_type = parts[:2]
        if doc_type not in DOC_TYPES:
            _finding(
                findings,
                "unknown_doc_type",
                entry["path"],
                "Tipo documental no reconocido",
                error=True,
            )
        key = (doc_type, unicodedata.normalize("NFC", path.stem))
        artifacts[(layer, *key)].append(entry["path"])
        if layer != "raw":
            continue
        doc = _new_document(entry["path"], doc_type)
        source_count += 1
        doc.update(
            {"format": path.suffix.lower(), "bytes": entry["bytes"], "sha256": entry["sha256"]}
        )
        owners[key].append(doc)
        documents.append(doc)
        duplicates[entry["sha256"]].append(entry["path"])
        folded_names[(doc_type, unicodedata.normalize("NFC", path.name).casefold())].append(
            entry["path"]
        )
        for condition, code, detail in (
            (
                path.name != unicodedata.normalize("NFC", path.name),
                "unicode_non_nfc",
                "Unicode descompuesto; no implica corrupción",
            ),
            ("  " in path.name, "double_spaces", "Nombre con espacios consecutivos"),
            (
                len(path.name.encode("utf-8")) > 180,
                "long_name",
                "Más de 180 bytes; aviso conservador de portabilidad, no nombre inválido",
            ),
            (
                path.stem.endswith("."),
                "trailing_dot",
                "Punto al final del nombre antes de la extensión",
            ),
            ("XXXX" in path.name, "placeholder_name", "Identificador provisional en el nombre"),
            (
                path.suffix != path.suffix.lower(),
                "uppercase_extension",
                "El pipeline distingue extensiones en minúscula",
            ),
        ):
            if condition:
                _finding(findings, code, entry["path"], detail)
        if path.suffix.lower() == ".pdf":
            with path.open("rb") as stream:
                offset = stream.read(1024).find(b"%PDF-")
                if offset < 0:
                    _finding(
                        findings,
                        "invalid_pdf_signature",
                        entry["path"],
                        "Firma PDF ausente en los primeros 1024 bytes",
                        error=True,
                    )
                elif offset:
                    _finding(
                        findings,
                        "pdf_header_offset",
                        entry["path"],
                        f"{offset} bytes antes de la firma PDF; aviso de compatibilidad, no prueba de corrupción",
                    )
    duplicate_groups = [paths for paths in duplicates.values() if len(paths) > 1]
    for paths in duplicate_groups:
        _finding(
            findings,
            "identical_source_bytes",
            paths[0],
            "Misma huella SHA-256: " + "; ".join(paths),
        )
    for paths in folded_names.values():
        if len(paths) > 1:
            _finding(
                findings,
                "portable_name_collision",
                paths[0],
                "Nombres equivalentes al normalizar Unicode y mayúsculas: " + "; ".join(paths),
            )
    # Mantener también derivados sin Raw. Nunca elegir un archivo ante ambigüedad.
    for (_, doc_type, stem), paths in artifacts.items():
        if (doc_type, stem) not in owners:
            reference = paths[0]
            doc = _new_document(reference, doc_type)
            owners[(doc_type, stem)].append(doc)
            documents.append(doc)
            _finding(findings, "missing_raw", reference, "Derivados sin fuente Raw identificable")
    for key, docs in owners.items():
        for layer in LAYERS:
            paths = artifacts.get((layer, *key), [])
            if len(docs) != 1 or len(paths) > 1:
                if paths:
                    _finding(
                        findings,
                        "ambiguous_layer_mapping",
                        paths[0],
                        f"Correspondencia ambigua en {layer}; no se asocia automáticamente",
                        error=True,
                    )
            elif paths:
                docs[0]["artifacts"][layer] = paths[0]
            else:
                _finding(findings, "missing_layer", docs[0]["source_path"], f"Sin archivo {layer}")
    by_gold = {doc["artifacts"]["gold"]: doc for doc in documents if "gold" in doc["artifacts"]}
    return documents, by_gold, duplicate_groups, source_count


def _audit_files(
    files: list[dict],
    project_root: Path,
    corpus: Path,
    by_gold: dict[str, dict],
    findings: list[dict],
) -> tuple[dict[str, tuple[str, str, dict[str, str], frozenset[str]]], set[str], int]:
    chunks: dict[str, tuple[str, str, dict[str, str], frozenset[str]]] = {}
    seen_gold_ids: set[str] = set()
    ambiguous_ids: set[str] = set()
    total_gold = 0
    for entry in files:
        path = project_root / entry["path"]
        layer = path.relative_to(corpus).parts[0]
        if path.suffix.lower() == ".json":
            try:
                _loads(path.read_text(encoding="utf-8"))
            except (ValueError, UnicodeError) as exc:
                _finding(findings, "invalid_json_file", entry["path"], str(exc), error=True)
        if layer in ("silver", "gold") and path.suffix.lower() == ".jsonl":
            records_read = 0
            findings_before = len(findings)
            for number, row in _records(path, findings, entry["path"]):
                records_read += 1
                text, metadata = row.get("page_content"), row.get("metadata")
                # Un ID reconocible se registra incluso si el contenido es inválido.
                # Así ninguna copia posterior puede quedar como asociación inequívoca.
                cid = metadata.get("chunk_id") if isinstance(metadata, dict) else None
                duplicate = False
                if layer == "gold" and isinstance(cid, str) and cid:
                    duplicate = cid in seen_gold_ids
                    seen_gold_ids.add(cid)
                    if duplicate:
                        chunks.pop(cid, None)
                        ambiguous_ids.add(cid)
                        _finding(
                            findings,
                            "duplicate_gold_id",
                            entry["path"],
                            cid,
                            error=True,
                            line=number,
                        )
                if not isinstance(text, str) or not isinstance(metadata, dict):
                    _finding(
                        findings,
                        "invalid_document_record",
                        entry["path"],
                        "Se requiere page_content textual y metadata objeto",
                        error=True,
                        line=number,
                    )
                    continue
                if not text.strip():
                    _finding(
                        findings,
                        "empty_silver_section" if layer == "silver" else "empty_gold_chunk",
                        entry["path"],
                        "Texto vacío; Silver se omite al fragmentar, Gold requiere contenido",
                        error=layer == "gold",
                        line=number,
                    )
                    continue
                if layer != "gold":
                    continue
                total_gold += 1
                doc = by_gold.get(entry["path"])
                if doc is not None:
                    doc["gold_chunks"] += 1
                    for key in DESCRIPTIVE_FIELDS:
                        value = metadata.get(key)
                        if isinstance(value, str) and value:
                            values = doc["observed_metadata"].setdefault(key, [])
                            if value not in values:
                                values.append(value)
                if not isinstance(cid, str) or not cid:
                    _finding(
                        findings,
                        "missing_chunk_id",
                        entry["path"],
                        "chunk_id debe ser texto no vacío",
                        error=True,
                        line=number,
                    )
                    continue
                if metadata.get("doc_type") != path.relative_to(corpus).parts[
                    1
                ] or unicodedata.normalize(
                    "NFC", str(metadata.get("source"))
                ) != unicodedata.normalize("NFC", path.stem + ".md"):
                    _finding(
                        findings,
                        "gold_source_type_mismatch",
                        entry["path"],
                        "source/doc_type no concuerdan con el archivo Gold",
                        error=True,
                        line=number,
                    )
                if duplicate:
                    continue
                try:
                    meta_hashes = _metadata_hashes(metadata, gold=True)
                except ValueError as exc:
                    _finding(
                        findings,
                        "invalid_gold_metadata",
                        entry["path"],
                        str(exc),
                        error=True,
                        line=number,
                    )
                    continue
                structured_fields = frozenset(
                    key for key, value in metadata.items() if isinstance(value, (list, dict))
                )
                chunks[cid] = (entry["path"], _value_digest(text), meta_hashes, structured_fields)
            if (
                layer == "gold"
                and entry["bytes"] > 0
                and records_read == 0
                and len(findings) == findings_before
            ):
                _finding(
                    findings,
                    "empty_gold_file",
                    entry["path"],
                    "Archivo Gold sin registros JSON documentales",
                    error=True,
                )
        if path.suffix.lower() == ".md":
            try:
                text = path.read_text(encoding="utf-8")
            except UnicodeError:
                _finding(
                    findings, "invalid_utf8", entry["path"], "Markdown no es UTF-8", error=True
                )
                continue
            if layer != "bronze":
                continue
            _audit_images(text, path, project_root, corpus, findings)
    return chunks, ambiguous_ids, total_gold


def build_catalog(project_root: Path, corpus: Path, export: Path | None = None) -> dict:
    project_root, corpus = project_root.resolve(), corpus.resolve()
    if not corpus.is_dir() or not corpus.is_relative_to(project_root):
        raise ValueError("El corpus debe ser un directorio dentro del proyecto")
    if export is not None:
        if export.is_symlink():
            raise ValueError("El export no puede ser un enlace simbólico")
        export = export.resolve()
        if not export.is_file() or not export.is_relative_to(project_root):
            raise ValueError("El export debe ser un archivo dentro del proyecto")
    files = _inventory(corpus, project_root)
    export_hash = _digest(export) if export is not None else None
    findings: list[dict] = []
    documents, by_gold, duplicate_groups, source_count = _collect_documents(
        files, project_root, corpus, findings
    )
    if not documents:
        _finding(
            findings,
            "no_corpus_documents",
            _relative(corpus, project_root),
            "No se encontraron documentos en la estructura Raw/Bronze/Silver/Gold",
            error=True,
        )
    chunks, ambiguous_ids, total_gold = _audit_files(files, project_root, corpus, by_gold, findings)
    evidence = None
    if export is not None:
        evidence = _compare_export(export, project_root, chunks, ambiguous_ids, by_gold, findings)
        evidence["sha256"] = export_hash
    for doc in documents:
        for key, values in doc["observed_metadata"].items():
            values.sort()
            if len(values) > 1:
                _finding(
                    findings,
                    "inconsistent_descriptive_metadata",
                    doc["source_path"],
                    f"Múltiples valores observados de {key}",
                )
    # Un catálogo no debe mezclar versiones si las fuentes cambian durante la lectura.
    if files != _inventory(corpus, project_root) or (
        export is not None and export_hash != _digest(export)
    ):
        raise ValueError(
            "Las entradas cambiaron durante la auditoría; repetir con una copia estable"
        )
    documents.sort(key=lambda doc: doc["source_path"])
    findings.sort(
        key=lambda item: (item["path"], item["code"], item.get("line", 0), item["detail"])
    )
    return {
        "schema_version": 1,
        "generator": GENERATOR,
        "scope": {
            "live_index": "not_verified",
            "legal_validity": "not_verified",
            "ocr_fidelity": "not_verified",
            "pdf_check": "signature_only",
            "metadata_origin": "observed_in_local_gold_not_new_legal_validation",
            "image_check": "simple_inline_or_angle_bracket_markdown_links_only",
        },
        "inputs": {
            "corpus_root": _relative(corpus, project_root),
            "files": files,
            "export": evidence,
        },
        "summary": {
            "source_files": source_count,
            "catalog_entries": len(documents),
            "gold_records": total_gold,
            "gold_unique_comparable_ids": len(chunks),
            "ambiguous_gold_ids": len(ambiguous_ids),
            "exact_duplicate_source_groups": len(duplicate_groups),
            "errors": sum(item["severity"] == "error" for item in findings),
            "warnings": sum(item["severity"] == "warning" for item in findings),
        },
        "identical_source_groups": duplicate_groups,
        "documents": documents,
        "findings": findings,
    }


def _compare_export(
    export: Path,
    project_root: Path,
    chunks: dict[str, tuple[str, str, dict[str, str], frozenset[str]]],
    ambiguous_ids: set[str],
    by_gold: dict[str, dict],
    findings: list[dict],
) -> dict:
    label = _relative(export, project_root)
    manifest = None
    seen: set[str] = set()
    sources: Counter = Counter()
    dimensions: Counter = Counter()
    counts: Counter[str] = Counter()
    field_diffs: Counter[str] = Counter()
    for number, row in _records(export, findings, label):
        if "__manifest__" in row:
            if manifest is not None or not isinstance(row["__manifest__"], dict):
                _finding(
                    findings,
                    "invalid_export_manifest",
                    label,
                    "Manifest inválido o repetido",
                    error=True,
                    line=number,
                )
            else:
                manifest = row["__manifest__"]
            continue
        counts["records"] += 1
        cid, text, metadata, embedding = (
            row.get(key) for key in ("id", "document", "metadata", "embedding")
        )
        duplicate = isinstance(cid, str) and bool(cid) and cid in seen
        if isinstance(cid, str) and cid:
            seen.add(cid)
            if duplicate:
                _finding(findings, "duplicate_export_id", label, cid, error=True, line=number)
        if (
            not isinstance(cid, str)
            or not cid
            or not isinstance(text, str)
            or not text.strip()
            or not isinstance(metadata, dict)
            or not isinstance(embedding, list)
            or not embedding
        ):
            _finding(
                findings,
                "invalid_export_record",
                label,
                "Se requiere id, document, metadata y embedding no vacío",
                error=True,
                line=number,
            )
            continue
        if duplicate:
            continue
        source, doc_type = metadata.get("source"), metadata.get("doc_type")
        if (
            not isinstance(source, str)
            or not source.strip()
            or not isinstance(doc_type, str)
            or doc_type not in DOC_TYPES
        ):
            _finding(
                findings,
                "invalid_export_source_type",
                label,
                "source debe ser texto no vacío y doc_type un tipo documental reconocido",
                error=True,
                line=number,
            )
            continue
        sources[(doc_type, source)] += 1
        dimensions[len(embedding)] += 1
        if cid in ambiguous_ids:
            counts["ids_ambiguous_in_gold"] += 1
            continue
        if cid not in chunks:
            counts["ids_missing_gold"] += 1
            continue
        gold_path, text_hash, expected_metadata, structured_fields = chunks[cid]
        counts["ids_matched"] += 1
        doc = by_gold.get(gold_path)
        if doc is not None:
            doc["export_records_matched_by_id"] += 1
        if _value_digest(text) != text_hash:
            counts["text_mismatches"] += 1
            if doc is not None:
                doc["export_text_mismatches"] += 1
        exported_metadata = _metadata_hashes(
            metadata, gold=False, structured_fields=structured_fields
        )
        differences = {
            key
            for key in expected_metadata.keys() | exported_metadata.keys()
            if expected_metadata.get(key) != exported_metadata.get(key)
        }
        if differences:
            counts["records_with_metadata_differences"] += 1
            field_diffs.update(differences)
            if doc is not None:
                for key in sorted(differences):
                    doc["export_metadata_differences"][key] = (
                        doc["export_metadata_differences"].get(key, 0) + 1
                    )
    for cid in chunks.keys() - seen:
        doc = by_gold.get(chunks[cid][0])
        if doc is not None:
            doc["gold_ids_missing_export"] += 1
    missing = len(chunks.keys() - seen)
    for key, count in (
        ("ids_missing_gold", counts["ids_missing_gold"]),
        ("gold_ids_missing_export", missing),
        ("text_mismatches", counts["text_mismatches"]),
        ("records_with_metadata_differences", counts["records_with_metadata_differences"]),
    ):
        if count:
            _finding(
                findings,
                key,
                label,
                f"{count} registros; diferencia de snapshots, no autorización para reemplazar datos",
            )
    if manifest is None:
        _finding(
            findings,
            "missing_export_manifest",
            label,
            "Fecha y colección del snapshot no certificadas",
        )
    elif manifest.get("count") != counts["records"]:
        _finding(
            findings,
            "export_manifest_count_mismatch",
            label,
            "El count del manifest difiere del número de registros",
            error=True,
        )
    return {
        "path": label,
        "collection": (manifest or {}).get("collection"),
        "created_at": (manifest or {}).get("created_at"),
        "format_version": (manifest or {}).get("format_version"),
        "manifest_count": (manifest or {}).get("count"),
        **{
            key: counts[key]
            for key in (
                "records",
                "ids_matched",
                "ids_missing_gold",
                "ids_ambiguous_in_gold",
                "text_mismatches",
                "records_with_metadata_differences",
            )
        },
        "gold_ids_missing_export": missing,
        "metadata_field_differences": dict(sorted(field_diffs.items())),
        "embedding_dimensions": {str(key): value for key, value in sorted(dimensions.items())},
        "sources": [
            {"doc_type": typ, "source": source, "records": count}
            for (typ, source), count in sorted(sources.items())
        ],
    }


def _md(value: Any) -> str:
    text = str(value).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    for symbol in ("\\", "|", "[", "]", "*", "`", "_"):
        text = text.replace(symbol, "\\" + symbol)
    return text.replace("\n", " ").replace("\r", " ")


def render_markdown(catalog: dict, output_dir: Path, project_root: Path) -> str:
    summary = catalog["summary"]
    evidence = catalog["inputs"]["export"]
    lines = [
        MARKDOWN_MARKER,
        "# Inventario técnico del corpus local",
        "",
        "Generado desde los archivos locales. No editar manualmente: regenerar ambos artefactos.",
        "",
        "**No confirma el índice desplegado, vigencia jurídica, calidad OCR ni cobertura completa.**",
        "La presencia de capas y la firma PDF no certifican fidelidad del procesamiento.",
        "",
        f"Archivos fuente: {summary['source_files']}. Entradas: {summary['catalog_entries']}. Chunks Gold leídos: {summary['gold_records']}.",
        f"Errores técnicos: {summary['errors']}. Advertencias: {summary['warnings']}.",
        "",
    ]
    if evidence:
        lines.extend(
            [
                f"Backup: {_md(evidence['path'])}. Colección: {_md(evidence['collection'])}. Fecha declarada: {_md(evidence['created_at'])}.",
                f"Registros: {evidence['records']}; IDs coincidentes: {evidence['ids_matched']}; textos diferentes: {evidence['text_mismatches']}; registros con diferencias de metadata: {evidence['records_with_metadata_differences']}.",
                "",
            ]
        )
    else:
        lines.extend(["No se suministró backup: presencia en un índice no comprobada.", ""])
    lines.extend(
        [
            "## Fuentes y capas",
            "",
            "Los títulos y metadatos observados, hashes y evidencias detalladas están en [corpus-catalog.json](corpus-catalog.json).",
            "",
            "| Fuente local / referencia del derivado | Tipo | Bronze | Silver | Gold | Chunks Gold | IDs en backup |",
            "|---|---|---|---|---|---|---|",
        ]
    )
    for doc in catalog["documents"]:
        path = doc["source_path"]
        relative = Path(os.path.relpath(project_root / path, output_dir)).as_posix()
        link = f"[{_md(Path(path).name)}]({quote(relative, safe='/')})"
        layers = [
            "Sí" if layer in doc["artifacts"] else "No / ambiguo"
            for layer in ("bronze", "silver", "gold")
        ]
        count = str(doc["export_records_matched_by_id"]) if evidence else "No comprobado"
        lines.append(
            f"| {link} | {_md(doc['doc_type'])} | {' | '.join(layers)} | {doc['gold_chunks']} | {count} |"
        )
    lines.extend(
        [
            "",
            "## Hallazgos",
            "",
            "Las advertencias no autorizan renombrados, borrados, reparaciones ni reindexaciones.",
            "",
        ]
    )
    for item in catalog["findings"]:
        location = item["path"] + (f":{item['line']}" if "line" in item else "")
        lines.append(
            f"- {_md(item['severity'])} / {_md(item['code'])}: {_md(location)} — {_md(item['detail'])}"
        )
    if not catalog["findings"]:
        lines.append(
            "Sin hallazgos en las comprobaciones implementadas; no equivale a validación jurídica."
        )
    return "\n".join(lines) + "\n"


def _write_outputs(
    output_dir: Path, contents: tuple[str, str], corpus: Path, export: Path | None
) -> None:
    targets = [output_dir / name for name in OUTPUT_NAMES]
    if output_dir.is_relative_to(corpus) or any(
        path == export or path.is_symlink() for path in targets
    ):
        raise ValueError("Los informes no pueden sobrescribir entradas ni usar enlaces simbólicos")
    for path in targets:
        if path.exists():
            if path.suffix == ".json":
                existing = _loads(path.read_text(encoding="utf-8"))
                owned = (
                    isinstance(existing, dict)
                    and existing.get("generator") == GENERATOR
                    and existing.get("schema_version") == 1
                )
            else:
                owned = path.read_text(encoding="utf-8").startswith(MARKDOWN_MARKER + "\n")
            if not owned:
                raise ValueError(f"No se sobrescribe un archivo ajeno: {path.name}")
    output_dir.mkdir(parents=True, exist_ok=True)
    for path, text in zip(targets, contents, strict=True):
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", dir=output_dir, delete=False
        ) as stream:
            temp = Path(stream.name)
            try:
                stream.write(text)
                stream.close()
                temp.replace(path)
            finally:
                temp.unlink(missing_ok=True)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project-root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--corpus", type=Path, default=Path("data/documents"))
    parser.add_argument(
        "--export",
        type=Path,
        help="Backup explícito; no se selecciona automáticamente el más reciente",
    )
    parser.add_argument("--output-dir", type=Path, default=Path("data"))
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--write", action="store_true", help="Escribir solo el JSON y Markdown derivados"
    )
    mode.add_argument(
        "--check", action="store_true", help="Comparar con los artefactos existentes, sin escribir"
    )
    args = parser.parse_args(argv)
    root = args.project_root.resolve()
    corpus = (root / args.corpus).resolve()
    export = root / args.export if args.export else None
    output_dir = (root / args.output_dir).resolve()
    try:
        if not output_dir.is_relative_to(root):
            raise ValueError("El directorio de informes debe estar dentro del proyecto")
        catalog = build_catalog(root, corpus, export)
        contents = (
            json.dumps(catalog, ensure_ascii=False, indent=2, sort_keys=True, allow_nan=False)
            + "\n",
            render_markdown(catalog, output_dir, root),
        )
        if args.check:
            for name, expected in zip(OUTPUT_NAMES, contents, strict=True):
                path = output_dir / name
                if (
                    not path.is_file()
                    or path.is_symlink()
                    or path.read_text(encoding="utf-8") != expected
                ):
                    print(f"Catálogo ausente o desactualizado: {name}")
                    return 1
            print("Catálogo vigente respecto de las entradas locales y del backup indicado.")
        elif args.write:
            _write_outputs(output_dir, contents, corpus, export.resolve() if export else None)
            print(
                f"Generados: {', '.join(OUTPUT_NAMES)}. Errores: {catalog['summary']['errors']}; advertencias: {catalog['summary']['warnings']}."
            )
        else:
            print(contents[1], end="")
        return 1 if catalog["summary"]["errors"] else 0
    except (OSError, ValueError) as exc:
        print(f"No se completó el inventario: {exc}")
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
